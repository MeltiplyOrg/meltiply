#!/usr/bin/env bash
# Writes the locally-managed Cloudflare Tunnel configuration that publishes the
# dev app and unified public site on stable hostnames.
#
# A named tunnel needs an ingress list mapping public hostnames to local
# services; a Quick Tunnel has no configuration file at all. All services are
# published from a single connector: the public-site rule is matched
# before the app rule, and the trailing catch-all is mandatory — cloudflared
# refuses to start without it.
#
# The app hostname fronts the Vite dev server, which already proxies /api/* to
# the API Worker, so the API needs no rule of its own.
#
#   tunnel-config.sh write <frontend-port> <public-port>
#   tunnel-config.sh validate
#   tunnel-config.sh rule <url>
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
config_dir="$repo_root/.dev-tunnel"
config_file="$config_dir/config.yml"
hostname_script="$repo_root/scripts/cloudflare-local/tunnel-hostname.mjs"

tunnel_name() {
  if [[ "${MELTIPLY_TUNNEL_SHARED:-0}" == "1" ]]; then
    printf '%s\n' "${MELTIPLY_TUNNEL_NAME:-meltiply-dev}"
    return 0
  fi
  node "$hostname_script" --tunnel-name
}

# Prints a derived hostname, or fails with a reason when it cannot be derived.
#
# @param $1 `app` or `public`.
hostname() {
  node "$hostname_script" --kind "$1"
}

# Prints the hostnames that need DNS records. Per-branch tunnels need explicit
# records because a wildcard CNAME has a single target; only the shared tunnel
# can use one wildcard.
#
# @param $1 `app` or `public`.
covered_hostname() {
  node "$hostname_script" --kind "$1" --coverage
}

# Writes config.yml for the app and public-site hostnames at the supplied ports.
write_config() {
  local frontend_port=$1 public_port=$2
  local name app_hostname public_hostname
  name="$(tunnel_name)"
  app_hostname="$(hostname app)"
  public_hostname="$(hostname public)"

  # A `credentials-file` is only needed when the tunnel JSON is not in the
  # default ~/.cloudflared location, which cloudflared finds by itself.
  local credentials_line=""
  if [[ -n "${MELTIPLY_TUNNEL_CREDENTIALS_FILE:-}" ]]; then
    credentials_line="credentials-file: ${MELTIPLY_TUNNEL_CREDENTIALS_FILE}"
  fi

  mkdir -p "$config_dir"
  # Single-quote every value: these come from the environment and a hostname or
  # path containing a quote would otherwise change the YAML structure.
  {
    printf '# Generated by scripts/cloudflare-local/tunnel-config.sh. Do not edit;\n'
    printf '# `make dev` rewrites this on every start so the dev ports always match.\n'
    printf 'tunnel: '"'"'%s'"'"'\n' "$name"
    [[ -z "$credentials_line" ]] || printf '%s\n' "$credentials_line"
    printf '\ningress:\n'
    # The public-site rule must precede the app wildcard: cloudflared
    # evaluates ingress top to bottom and takes the first match.
    printf '  - hostname: %s\n' "$(quote "$public_hostname")"
    printf '    service: http://127.0.0.1:%s\n' "$public_port"
    if [[ "${MELTIPLY_TUNNEL_SHARED:-0}" == "1" &&
      "${MELTIPLY_TUNNEL_HOST_STYLE:-wildcard}" == "wildcard" ]]; then
      # Only meaningful for the single shared tunnel: a wildcard record and a
      # wildcard rule both need a one-to-one target, which a per-branch tunnel
      # cannot have.
      printf '  - hostname: %s\n' "$(quote "*.${MELTIPLY_TUNNEL_DEV_LABEL:-dev}.${MELTIPLY_TUNNEL_DOMAIN:?Set MELTIPLY_TUNNEL_DOMAIN to a domain you own}")"
    else
      printf '  - hostname: %s\n' "$(quote "$app_hostname")"
    fi
    printf '    service: http://127.0.0.1:%s\n' "$frontend_port"
    # Mandatory catch-all; without it cloudflared refuses to start.
    printf '  - service: http_status:404\n'
  } >"$config_file"

  printf '%s\n' "$config_file"
}

# Wraps a value in single quotes for YAML.
#
# @param $1 Raw value.
# @returns Quoted value with any embedded single quote doubled.
quote() {
  local value=$1
  value=${value//\'/\'\'}
  printf "'%s'" "$value"
}

# Validates the generated ingress rules with cloudflared itself, so a malformed
# rule fails here rather than as a connector that silently routes nothing.
validate_config() {
  local cloudflared
  cloudflared="$("$repo_root/scripts/cloudflare-local/dev-tunnel.sh" binary 2>/dev/null)" || {
    printf 'cloudflared is not installed; cannot validate %s\n' "$config_file" >&2
    return 1
  }
  "$cloudflared" --config "$config_file" tunnel ingress validate
}

# Reports which ingress rule a URL matches; used to prove routing is correct.
#
# @param $1 URL to test.
ingress_rule() {
  local cloudflared
  cloudflared="$("$repo_root/scripts/cloudflare-local/dev-tunnel.sh" binary 2>/dev/null)" || {
    printf 'cloudflared is not installed\n' >&2
    return 1
  }
  "$cloudflared" --config "$config_file" tunnel ingress rule "$1"
}

case "${1:-}" in
  write)
    [[ $# -eq 3 ]] || {
      printf 'usage: %s write <frontend-port> <public-port>\n' "$0" >&2
      exit 2
    }
    write_config "$2" "$3"
    ;;
  coverage)
    [[ $# -eq 2 ]] || {
      printf 'usage: %s coverage <app|public>\n' "$0" >&2
      exit 2
    }
    covered_hostname "$2"
    ;;
  validate) validate_config ;;
  rule)
    [[ $# -eq 2 ]] || {
      printf 'usage: %s rule <url>\n' "$0" >&2
      exit 2
    }
    ingress_rule "$2"
    ;;
  path) printf '%s\n' "$config_file" ;;
  *)
    printf 'usage: %s {write <frontend-port> <public-port>|coverage <kind>|validate|rule <url>|path}\n' \
      "$0" >&2
    exit 2
    ;;
esac
