const whitespacePattern = /\s/;
const byteOrderMarkPattern = /^\uFEFF/;

function stripJsonComments(source) {
  let result = "";
  let inString = false;
  let escaped = false;
  for (let index = 0; index < source.length; index += 1) {
    const current = source[index];
    const next = source[index + 1];
    if (inString) {
      result += current;
      if (escaped) escaped = false;
      else if (current === "\\") escaped = true;
      else if (current === '"') inString = false;
      continue;
    }
    if (current === '"') {
      inString = true;
      result += current;
      continue;
    }
    if (current === "/" && next === "/") {
      while (index < source.length && source[index] !== "\n") index += 1;
      result += "\n";
      continue;
    }
    if (current === "/" && next === "*") {
      index += 2;
      while (index < source.length && !(source[index] === "*" && source[index + 1] === "/")) {
        if (source[index] === "\n") result += "\n";
        index += 1;
      }
      if (index >= source.length) throw new TypeError("unterminated JSONC comment");
      index += 1;
      continue;
    }
    result += current;
  }
  if (inString) throw new TypeError("unterminated JSONC string");
  return result;
}

function stripTrailingCommas(source) {
  let result = "";
  let inString = false;
  let escaped = false;
  for (let index = 0; index < source.length; index += 1) {
    const current = source[index];
    if (inString) {
      result += current;
      if (escaped) escaped = false;
      else if (current === "\\") escaped = true;
      else if (current === '"') inString = false;
      continue;
    }
    if (current === '"') {
      inString = true;
      result += current;
      continue;
    }
    if (current === ",") {
      let lookahead = index + 1;
      while (whitespacePattern.test(source[lookahead] ?? "")) lookahead += 1;
      if (source[lookahead] === "}" || source[lookahead] === "]") continue;
    }
    result += current;
  }
  return result;
}

export function parseJsonc(source, name = "JSONC input") {
  try {
    return JSON.parse(
      stripTrailingCommas(stripJsonComments(source.replace(byteOrderMarkPattern, ""))),
    );
  } catch (error) {
    throw new TypeError(`${name} is invalid: ${error.message}`);
  }
}
